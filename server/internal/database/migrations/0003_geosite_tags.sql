-- 0003_geosite_tags: the geosite tag catalogue this server serves itself.
--
-- GET /api/v1/geosite reads this table. Before it existed the frontend fetched
-- the list from a separate service on :5001 that this repository did not
-- contain — the last piece of local development that needed an out-of-repo
-- service. The seed data below is that service's list, one row per tag.
--
-- is_category marks the curated bundles (CATEGORY-ADS-ALL and friends) that a
-- rule usually references, and idx_geosite_tags_sort makes the read path's
-- ordering — categories first, then alphabetical — an index scan.
--
-- Refreshing the catalogue is deliberately a migration rather than runtime
-- fetching: TRUNCATE and re-INSERT in a new versioned file. Every deployment
-- then sees the same list without this server needing outbound access, and the
-- checksum record says exactly when and how the list changed.

CREATE TABLE geosite_tags (
    name        varchar(64) PRIMARY KEY,
    is_category boolean NOT NULL,
    created_at  timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX idx_geosite_tags_sort ON geosite_tags (is_category DESC, name);

